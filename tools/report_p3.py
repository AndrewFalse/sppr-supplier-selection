"""Текст практики №3 (риски и неопределённость) для паспорта СППР. Числа берутся из outputs/p3."""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "p3"
FIG_MARK = "[ВСТАВИТЬ РИСУНОК: outputs/p3/decision_tree.png, ширина 13,5 см]"


def num(x, d=2):
    return f"{x:.{d}f}".replace(".", ",")


def mln(x, d=2):
    return num(x / 1e6, d)


def pct(x, d=0):
    return num(x * 100, d) + " %"


def content():
    s = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))
    cfg = json.loads((ROOT / "config" / "p3_risk.json").read_text(encoding="utf-8"))
    st = pd.read_csv(OUT / "strategies.csv", index_col=0)
    cr = pd.read_csv(OUT / "criteria.csv", index_col=0)
    vp = pd.read_csv(OUT / "vendors_params.csv")
    fx = pd.DataFrame(s["fx"])
    sup = cfg["supply"]
    pr = cfg["project"]
    key = s["key_rate"]
    tv = s["tree_values"]
    opt = s["optimization"]
    th = s["thresholds"]
    n_cx = pr["n_complexes"]

    c1 = cfg["strategies"]["С1"]["mix"]
    base = sum(vp[(vp.category == c) & (vp.vendor == v)]["unit_cost"].iloc[0] for c, m in c1.items() for v in m) * n_cx
    holding = base * (key * pr["horizon_days"] / 365 + pr["storage_rate"])

    fxp = {r["scenario"]: r for r in s["fx"]}
    t5 = [["Канал поставки", "в срок", "задержка", "срыв"]]
    labels = [("russian_manufacturer", "российский производитель"), ("official_distributor", "официальный дистрибьютор"),
              ("unknown", "статус в РФ не подтверждён"), ("left_ru_parallel_import", "параллельный импорт"),
              ("left_ru_excluded_from_parallel_import", "исключён из перечня параллельного импорта")]
    for key_s, label in labels:
        p = sup[key_s]
        t5.append([label, num(p["on_time"]), num(p["delay"]), num(p["fail"])])
    fx_text = ", ".join(f"{k} ({'+' if fxp[k]['delta'] > 0 else ''}{num(fxp[k]['delta'] * 100, 1)} %, p = {num(fxp[k]['prob'])})"
                        for k in ("укрепление", "стабильно", "ослабление"))

    t6 = [["Стратегия", "E, млн ₽", "CVaR95", "Вальд", "Сэвидж", "Гурвиц", "P (в срок)"]]
    names = {k: v["name"] for k, v in cfg["strategies"].items()}
    for sid in ["С1", "С2", "С3", "С4"]:
        t6.append([f"{sid} {names[sid]}", mln(tv[sid]), mln(st.loc[sid, "cvar95"]),
                   mln(cr.loc[sid, "Вальд (худший случай)"]), mln(cr.loc[sid, "Сэвидж (макс. сожаление)"]),
                   mln(cr.loc[sid, "Гурвиц"]), num(s["state_probs"][sid]["в срок"])])

    best = s["tree_best"]
    blocks = [
        ("title", "ПАСПОРТ СППР"),
        ("subtitle", "Выбор поставщиков оборудования для диспетчерских комплексов"),
        ("author", "Выполнил: Новосельцев Андрей Алексеевич, группа К4241"),
        ("h1", "3 РИСКИ И НЕОПРЕДЕЛЁННОСТЬ"),
        ("h2", "3.1 Постановка"),
        ("p", f"Задача - выбрать стратегию закупки для крупного проекта ({n_cx} типовых диспетчерских комплексов), когда курс рубля, сроки поставки и доступность каналов заранее неизвестны. Стратегии: С1 - всё у лидеров АНР (метода анализа иерархий) из практики № 2 с оплатой при поставке; С2 - зарубежный премиум (APC, Adder, HP Aruba, HP); С3 - диверсификация: объём каждой категории делится между лидером и вторым местом 60/40; С4 - набор С1, закупленный сразу со страховым запасом. Критерий - затраты на проект: закупка с учётом курса, замена сорванной поставки с наценкой {pct(sup['urgency_premium'])}, пени и простой бригады, для С4 - стоимость денег и хранения."),
        ("h2", "3.2 Метод"),
        ("p", f"Курс: изменение курса доллара за 91 день по официальным курсам ЦБ РФ за 2023-2026 гг. даёт сценарии {fx_text}. Исходы поставки по типу канала - экспертные оценки аналитика, так как открытой статистики нет (таблица 5): задержка - {sup['delay_days'] // 7} недели, срыв - поиск замены и поставка за {sup['fail_days'] // 7} недель. Пеня - 1/300 ключевой ставки ({pct(key)}) в день от цены договора, по аналогии с 44-ФЗ (законом о контрактной системе)."),
        ("caption", "Таблица 5 – Вероятности исходов поставки по типу канала (экспертные оценки)"),
        ("table", "T5"),
        ("p", f"Модель - дерево решений (рисунок 1, networkx): решение - 4 стратегии, случай - курс (3 сценария) и поставка (в срок, задержка, срыв); ожидаемые затраты E получены свёрткой дерева. Затраты в исходах рассчитаны методом Монте-Карло ({cfg['analysis']['mc_samples'] // 1000} тыс. испытаний). Стратегии сравниваются по критериям Байеса (E), Вальда (худший случай), Сэвиджа (максимальное сожаление), Гурвица (вес худшего исхода {num(cfg['analysis']['hurwicz_pessimism'], 1)}) и CVaR95 - средним затратам в 5 % худших исходов. Через scipy.optimize найдены оптимальная доля лидера в С3 (minimize_scalar) и пороги смены лучшей стратегии (brentq)."),
        ("h2", "3.3 Результат"),
        ("fig", FIG_MARK),
        ("figcap", "Рисунок 1 – Дерево решений, ожидаемые затраты в млн руб. (раскрыта стратегия С1)"),
        ("caption", "Таблица 6 – Сравнение стратегий, млн ₽"),
        ("table", "T6"),
        ("p", f"Лучшая по дереву решений - {best}: E = {mln(tv[best])} млн ₽ против {mln(tv['С1'])} млн ₽ у С1; она же лучшая по Вальду, Гурвицу и CVaR95, а разброс затрат у неё в {num(st.loc['С1', 'std'] / st.loc['С4', 'std'], 1)} раза меньше. По Сэвиджу выигрывает С3 (при укреплении рубля С4 переплачивает). С2 хуже по всем критериям: E выше на {pct(tv['С2'] / tv['С1'] - 1)}, вероятность поставки в срок {num(s['state_probs']['С2']['в срок'])}. Оптимальная доля лидера в С3 - {num(opt['risk_neutral']['x'])} для нейтрального к риску ЛПР и {num(opt['risk_averse']['x'])} при учёте риска: ограничение «не более 60 %» из практики № 1 почти ничего не стоит. Пороги: С4 лучше С1, пока вероятности задержек и срывов не ниже {pct(th['prob_scale_C1_eq_C4'])} от принятых и пока ключевая ставка ниже {pct(th['key_rate_C1_eq_C4'], 1)}."),
        ("h2", "3.4 Интерпретация"),
        ("p", f"Директору рекомендуется опережающая закупка у лидеров АНР: около {mln(holding, 1)} млн ₽ на стоимость денег и хранение снимают влияние курса и сроков и сужают разброс затрат. Если свободных средств нет, разумна С3 с долей лидера 50-60 %. Зарубежный премиум не оправдан. Вывод чувствителен к экспертным вероятностям поставки: если реальные срывы и задержки случаются заметно реже принятого (менее {pct(th['prob_scale_C1_eq_C4'])} от оценок), выгоднее покупать по факту поставки. Результаты передаются в практики № 4 и 5."),
    ]
    tables = {
        "T5": {"cols": [235.7, 77, 77, 78], "rows": t5, "align": ["START", "CENTER", "CENTER", "CENTER"]},
        "T6": {"cols": [136, 60, 56, 54, 56, 54, 51.7], "rows": t6, "align": ["START"] + ["CENTER"] * 6},
    }
    return blocks, tables


if __name__ == "__main__":
    b, t = content()
    for k, v in b:
        print(k, "|", v[:140])
    for name, spec in t.items():
        print(name)
        for row in spec["rows"]:
            print("   ", row)

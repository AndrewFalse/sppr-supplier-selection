           ["Показатели", "курс сейчас и через 13 недель, стоимость плана сейчас и через 3 месяца, ошибка прогноза", "какова ситуация и насколько верить прогнозу"],
           ["Курс USD/RUB", "факт ЦБ РФ и прогноз с интервалом 80 %", "чего ждать от курса"],
